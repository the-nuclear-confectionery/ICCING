#ifndef Mask_H
#define Mask_H
//__________________________________________________________________________________________
//##########################################################################################
//  C++ Libraries
//##########################################################################################
#include <iostream>
#include <string>
#include <cmath>
#include <vector>
//__________________________________________________________________________________________

using namespace std;

class IO;

class Mask
{
private:
  //__________________________________________________________________________________________
  //##########################################################################################
  //  Mask Parameters
  //##########################################################################################
  string mask_type;

  double dist_rad;
  double grid_step;
  double tau_;

  vector<vector<double>> dist_mask;  //  Sample from initial_energy for ICCING algorithm
  //__________________________________________________________________________________________

  //__________________________________________________________________________________________
  //##########################################################################################
  //  Internal Functions
  //##########################################################################################
	//  Copy function for Mask class, called by operator= and implicit copy functions
	void CopyMask(const Mask &e);

  void UniformMask();
  void GaussianMask();
  void KernelMask();
  void GreensFunctionMask();
  //__________________________________________________________________________________________

public:
  //__________________________________________________________________________________________
  //##########################################################################################
  //  Basic Class Functions
  //##########################################################################################
  Mask(string type, double rad, double gridstep, double tau);  // Class Constructor
  ~Mask();  //  Class Destructor

  Mask(const Mask &original); //  Implicit copy function, newIOObject(oldIOObject)
  Mask& operator=(const Mask& original);  //  Defines what happens when you use = operator on class
  //__________________________________________________________________________________________

  //__________________________________________________________________________________________
  //##########################################################################################
  //  Internal Functions
  //##########################################################################################
  double GetMaskSize() { return dist_mask.size(); }
  double GetMaskValue(int x, int y) { return dist_mask[x][y]; }
  //__________________________________________________________________________________________
};
#endif
